/**
 * Shared integrity checks for ArtemisKit benchmark packs.
 *
 * Every pack's `pack.test.ts` calls `definePackContractTests`. The checks keep a pack honest
 * after edits: the experiment manifest must declare exactly the task files on disk with matching
 * digests, workload and rubric identities must recompute, scoring must stay deterministic,
 * optional answer keys must accept null as well as omission, and every case must accept its
 * reference answer while rejecting wrong decisions.
 *
 * Pack layout:
 *   <pack>/tasks/<task-id>.yaml       scenario_evaluation tasks
 *   <pack>/reference/answers.yaml     { <scenario name>: { <case id>: { answer, fail_answers? } } }
 *   <pack>/experiment.yaml            generated by packs/_tools/generate-experiment.ts
 *   <pack>/RUBRIC.md                  rubric identity source
 */

import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  type Expected,
  type Scenario,
  getEvaluator,
  parseExperimentManifest,
  parseScenarioString,
} from '@artemiskit/core';
import { compareCodeUnits, listTaskPaths, sha256, workloadDigest } from './pack-contract-digests';

export interface PackContractOptions {
  /** Absolute pack directory, usually `import.meta.dir`. */
  packDir: string;
  /** Pack identifier, used in the `pack:<id>` tag and the `<id>-draft` experiment ID. */
  packId: string;
  /** Domain tag value, used in the `domain:<domain>` tag. */
  domain: string;
  /** BCP 47 language of every task, used in the `lang:<language>` tag. */
  language: string;
  /** Minimum number of tasks the pack must contain. */
  minTasks: number;
  /** Inclusive bounds on cases per task. */
  casesPerTask: { min: number; max: number };
}

/** Evaluators that need a model or arbitrary code; packs must not use them. */
const NON_DETERMINISTIC_TYPES = new Set(['llm_grader', 'similarity', 'inline', 'custom']);

type ReferenceAnswer = Record<string, unknown> & { decision: string };
type ReferenceCase = { answer: ReferenceAnswer; fail_answers?: ReferenceAnswer[] };
type ReferenceFile = Record<string, Record<string, ReferenceCase>>;

function expectationTypes(expected: Expected): string[] {
  if (expected.type === 'combined') {
    return [expected.type, ...expected.expectations.map((item) => item.type)];
  }
  return [expected.type];
}

function decisionValues(expected: Expected): string[] {
  if (expected.type !== 'combined') return [];
  const schemaExpectation = expected.expectations.find((item) => item.type === 'json_schema');
  if (schemaExpectation?.type !== 'json_schema') return [];
  const properties = schemaExpectation.schema.properties as
    | Record<string, { enum?: string[] }>
    | undefined;
  return properties?.decision?.enum ?? [];
}

function answerSchema(expected: Expected): Record<string, unknown> | undefined {
  const items = expected.type === 'combined' ? expected.expectations : [expected];
  const schemaExpectation = items.find((item) => item.type === 'json_schema');
  return schemaExpectation?.type === 'json_schema' ? schemaExpectation.schema : undefined;
}

type SchemaNode = {
  properties?: Record<string, SchemaNode>;
  required?: string[];
  items?: SchemaNode;
};

/**
 * Lists the optional (non-required) object properties, at any depth, whose schema rejects null.
 * Models often write `"key": null` for a key the prompt says to omit; scoring must treat that the
 * same as omission, so every optional key has to accept null.
 */
async function optionalKeysRejectingNull(schema: SchemaNode, path = '$'): Promise<string[]> {
  const rejecting: string[] = [];
  const required = new Set(schema.required ?? []);
  for (const [key, property] of Object.entries(schema.properties ?? {})) {
    const propertyPath = `${path}.${key}`;
    const acceptsNull = await passes('null', { type: 'json_schema', schema: property });
    if (!required.has(key) && !acceptsNull) rejecting.push(propertyPath);
    rejecting.push(...(await optionalKeysRejectingNull(property, propertyPath)));
  }
  if (schema.items) rejecting.push(...(await optionalKeysRejectingNull(schema.items, `${path}[]`)));
  return rejecting;
}

async function passes(response: string, expected: Expected): Promise<boolean> {
  const result = await getEvaluator(expected.type).evaluate(response, expected);
  return result.passed;
}

export function definePackContractTests(options: PackContractOptions): void {
  const { packDir, packId, domain, language, minTasks, casesPerTask } = options;
  const read = (relativePath: string) => readFileSync(join(packDir, relativePath));
  const loadScenario = (relativePath: string): Scenario =>
    parseScenarioString(read(relativePath).toString('utf8'), relativePath);

  const manifest = parseExperimentManifest(
    Bun.YAML.parse(read('experiment.yaml').toString('utf8'))
  );
  const taskPaths = listTaskPaths(packDir);
  const references = Bun.YAML.parse(
    read('reference/answers.yaml').toString('utf8')
  ) as ReferenceFile;

  describe(`${packId} experiment manifest`, () => {
    test('parses with the core experiment parser as a draft fixture experiment', () => {
      expect(manifest.id).toBe(`${packId}-draft`);
      expect(manifest.mode).toBe('fixture');
      expect(manifest.tasks.every((task) => task.kind === 'scenario_evaluation')).toBe(true);
    });

    test(`contains at least ${minTasks} tasks`, () => {
      expect(taskPaths.length).toBeGreaterThanOrEqual(minTasks);
    });

    test('declares every task file exactly once', () => {
      const declared = manifest.tasks.map((task) => task.source.path).sort(compareCodeUnits);
      expect(declared).toEqual(taskPaths);
    });

    test('task digests match the exact file bytes', () => {
      for (const task of manifest.tasks) {
        expect({ path: task.source.path, digest: task.source.artifact.digest }).toEqual({
          path: task.source.path,
          digest: sha256(read(task.source.path)),
        });
      }
    });

    test('workload and rubric identities recompute', () => {
      const pairs = manifest.tasks.map(
        (task) => [task.source.path, task.source.artifact.digest] as const
      );
      expect(manifest.identities.workload.digest).toBe(workloadDigest(pairs));
      expect(manifest.identities.rubric.digest).toBe(sha256(read('RUBRIC.md')));
    });

    test('task IDs, file names and languages agree', () => {
      for (const task of manifest.tasks) {
        expect(task.source.path).toBe(`tasks/${task.id}.yaml`);
        expect(task.language).toBe(language);
      }
    });

    test('targets are local open-weight deployments with cost not applicable', () => {
      for (const target of manifest.targets) {
        expect(target.deployment).toMatchObject({
          locality: 'local',
          cost_basis: 'not_applicable',
        });
        expect(target.weights?.availability).toBe('open');
        expect(target.publisher).toBeDefined();
      }
    });
  });

  describe(`${packId} task files`, () => {
    test.each(taskPaths)('%s parses as a scenario with pack tags', (relativePath) => {
      const scenario = loadScenario(relativePath);
      expect(scenario.tags).toContain(`pack:${packId}`);
      expect(scenario.tags).toContain(`domain:${domain}`);
      expect(scenario.tags).toContain(`lang:${language}`);
      expect(scenario.tags).toContain('status:draft-unreviewed');
      expect(scenario.description).toContain('synthetic');
      expect(scenario.setup?.systemPrompt).toContain('SYNTHETIC RULEBOOK');
      expect(scenario.cases.length).toBeGreaterThanOrEqual(casesPerTask.min);
      expect(scenario.cases.length).toBeLessThanOrEqual(casesPerTask.max);
    });

    test.each(taskPaths)('%s uses only deterministic expectations', (relativePath) => {
      for (const testCase of loadScenario(relativePath).cases) {
        const types = expectationTypes(testCase.expected);
        expect(types.filter((type) => NON_DETERMINISTIC_TYPES.has(type))).toEqual([]);
        expect(types).toContain('json_schema');
      }
    });

    test.each(taskPaths)('%s: optional answer keys accept null', async (relativePath) => {
      const scenario = loadScenario(relativePath);
      for (const testCase of scenario.cases) {
        const schema = answerSchema(testCase.expected) as SchemaNode;
        const label = `${scenario.name}/${testCase.id}`;
        expect({ label, rejectingNull: await optionalKeysRejectingNull(schema) }).toEqual({
          label,
          rejectingNull: [],
        });
      }
    });

    test('scenario names are unique across the pack', () => {
      const names = taskPaths.map((path) => loadScenario(path).name);
      expect(new Set(names).size).toBe(names.length);
    });
  });

  describe(`${packId} reference answers`, () => {
    test.each(taskPaths)('%s: every case has a reference answer', (relativePath) => {
      const scenario = loadScenario(relativePath);
      const caseIds = scenario.cases.map((testCase) => testCase.id).sort(compareCodeUnits);
      expect(Object.keys(references[scenario.name] ?? {}).sort(compareCodeUnits)).toEqual(caseIds);
    });

    test.each(taskPaths)(
      '%s: expectations accept references and reject wrong decisions',
      async (relativePath) => {
        const scenario = loadScenario(relativePath);
        for (const testCase of scenario.cases) {
          await assertCaseScoring(
            `${scenario.name}/${testCase.id}`,
            references[scenario.name][testCase.id],
            testCase.expected
          );
        }
      }
    );
  });
}

async function assertCaseScoring(
  label: string,
  reference: ReferenceCase,
  expected: Expected
): Promise<void> {
  const pretty = JSON.stringify(reference.answer, null, 2);
  expect({ label, passed: await passes(pretty, expected) }).toEqual({ label, passed: true });
  const fenced = `\`\`\`json\n${pretty}\n\`\`\``;
  expect({ label, fenced: await passes(fenced, expected) }).toEqual({ label, fenced: true });

  const wrongDecisions = decisionValues(expected).filter(
    (value) => value !== reference.answer.decision
  );
  expect(wrongDecisions.length).toBeGreaterThan(0);
  for (const decision of wrongDecisions) {
    const wrong = JSON.stringify({ ...reference.answer, decision });
    expect({ label, decision, passed: await passes(wrong, expected) }).toEqual({
      label,
      decision,
      passed: false,
    });
  }

  for (const [index, failAnswer] of (reference.fail_answers ?? []).entries()) {
    const response = JSON.stringify(failAnswer);
    expect({ label, index, passed: await passes(response, expected) }).toEqual({
      label,
      index,
      passed: false,
    });
  }

  const prose = `Decision: ${reference.answer.decision}. ${pretty}`;
  expect({ label, prose: await passes(prose, expected) }).toEqual({ label, prose: false });
}
